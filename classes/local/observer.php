class observer {
    /**
     * Remove a deleted user's screenshots.
     *
     * @param \core\event\user_deleted $event
     * @return void
     */
    public static function user_deleted(\core\event\user_deleted $event): void {
        manager::delete_all_for_user($event->objectid, $event->contextid);
    }
}
